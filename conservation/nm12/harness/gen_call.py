#!/usr/bin/env python3
"""Generate hv_mod.F90 (allocatable copies of every noahmpdrv_run dummy) and hv_call.inc (keyword call).

Usage: gen_call.py <drv_head.f90> <outdir>
drv_head.f90 = noahmpdrv.F90 from 'subroutine noahmpdrv_run' to the end of its declarations.
"""
import re, sys, os

src, out = sys.argv[1], sys.argv[2]
lines = open(src).read().splitlines()
decl = re.compile(r'^\s*(real\(kind=kind_phys\)|integer|logical|character\(len=\*\))\s*(.*?)intent\((in|out|inout)\)\s*(.*?)::\s*(\w+)', re.I)
SNOW = {'tsnoxy': '-2:0', 'snicexy': '-2:0', 'snliqxy': '-2:0', 'zsnsoxy': '-2:4'}
vars_ = []
for ln in lines:
    m = decl.match(ln)
    if not m:
        continue
    typ, mid, intent, mid2, name = m.groups()
    attrs = (mid + ' ' + mid2).lower()
    if 'optional' in attrs:
        continue
    dm = re.search(r'dimension\(([^)]*)\)', attrs)
    dims = dm.group(1).replace(' ', '') if dm else ''
    vars_.append((typ.lower(), dims, name))

decls, allocs = [], []
for typ, dims, name in vars_:
    t = {'real(kind=kind_phys)': 'real(kind_phys)', 'integer': 'integer', 'logical': 'logical',
         'character(len=*)': 'character(len=512)'}[typ]
    if dims == '':
        decls.append(f'  {t} :: {name}')
    elif dims == ':':
        decls.append(f'  {t}, allocatable :: {name}(:)')
        allocs.append(f'    allocate({name}(im))')
    elif dims == ':,:':
        decls.append(f'  {t}, allocatable :: {name}(:,:)')
        allocs.append(f'    allocate({name}(im,km))')
    elif dims == ':,lsnowl:':
        decls.append(f'  {t}, allocatable :: {name}(:,:)')
        allocs.append(f'    allocate({name}(im,{SNOW[name]}))')
    else:
        raise SystemExit(f'unhandled dims {dims} for {name}')

with open(os.path.join(out, 'hv_mod.F90'), 'w') as f:
    f.write('! generated by gen_call.py: every non-optional noahmpdrv_run dummy as a module variable\n')
    f.write('module hv_mod\n  use machine, only: kind_phys\n  implicit none\n')
    f.write('\n'.join(decls) + '\ncontains\n  subroutine hv_alloc()\n')
    f.write('\n'.join(allocs) + '\n  end subroutine hv_alloc\nend module hv_mod\n')

args = [f'{n}={n}' for _, _, n in vars_] + ['iter=1']
body = '    call noahmpdrv_run( &\n'
body += ', &\n'.join('      ' + a for a in args) + ')\n'
open(os.path.join(out, 'hv_call.inc'), 'w').write(body)
print(len(vars_), 'dummies')
